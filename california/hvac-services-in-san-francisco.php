                        </h2>

                        <p class="ehs-hvac-signs-intro">
                            HVAC performance problems can affect indoor comfort, airflow, and energy use. Recognizing common warning signs can help San Francisco homeowners determine when professional inspection or repair may be necessary.
                        </p>
                        <ul class="ehs-hvac-signs-list">

                            <li class="ehs-hvac-signs-item"><strong>Uneven indoor temperatures:</strong> If certain rooms remain colder or warmer than others, the issue may involve ductwork, insulation, <a class="ehs-hvac-internal-link" href="https://easyhomeservice.com/blog/thermostat-replacement-cost-repair-vs-replace">thermostat placement</a>, or restricted airflow.</li>
<li class="ehs-hvac-signs-item"><strong>Weak airflow from vents:</strong> Reduced airflow can result from clogged filters, blocked vents, duct leaks, or <a class="ehs-hvac-internal-link" href="https://easyhomeservice.com/blog/hvac-blower-motor-repair">blower-related problems</a> that require inspection.</li>
<li class="ehs-hvac-signs-item"><strong>Heating problems:</strong> A furnace or heat pump that struggles to maintain the desired temperature may have dirty filters, worn components, control issues, or airflow restrictions.</li>
<li class="ehs-hvac-signs-item"><strong>Unexpected cooling problems:</strong> If your AC struggles during warmer weather, possible causes include refrigerant issues, dirty components, airflow restrictions, or equipment performance problems.</li>
<li class="ehs-hvac-signs-item"><strong>Unusual HVAC noises:</strong> Rattling, grinding, buzzing, or persistent clicking sounds can indicate loose components or mechanical problems.</li>
<li class="ehs-hvac-signs-item"><strong>Frequent system cycling:</strong> An HVAC system that repeatedly switches on and off may have thermostat, airflow, sizing, or equipment-related issues.</li>
<li class="ehs-hvac-signs-item"><strong>Rising energy bills:</strong> An unexplained increase in energy consumption may indicate reduced system efficiency or equipment problems.</li>
<li class="ehs-hvac-signs-item"><strong>Persistent indoor odors:</strong> Unusual smells coming from vents or HVAC equipment may indicate filter, drainage, moisture, or other system concerns.</li>

                        </ul>
                        <p class="ehs-hvac-signs-intro">
                            These symptoms can have different causes, including airflow restrictions, dirty filters, ductwork concerns, thermostat problems, drainage issues, electrical components, or equipment wear. A professional inspection can help determine what requires attention rather than assuming every symptom has the same solution.
