    <section class="ehs-hvac-challenges-section">
        <div class="container">
            <div class="row justify-content-center">
                <div class="col-12 col-lg-8">
                    <div class="ehs-hvac-challenges-container">
                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems Washington Homeowners Face
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Furnace Short Cycling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Your furnace turns on and off in quick bursts, often from a clogged filter, a failing flame sensor, or an oversized unit. Short cycling wastes energy, leaves rooms uneven, and strains components during Washington's chilly, damp months.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Weak Airflow From Vents</h3>
                            <p class="ehs-hvac-challenges-text">
                                Rooms that feel stuffy or never reach the thermostat setting often point to dirty filters, blocked returns, leaking ducts, or a struggling blower motor. Many older Washington homes also have ductwork that was never properly sealed.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heat Pump Not Heating Properly</h3>
                            <p class="ehs-hvac-challenges-text">
                                Heat pumps are popular across Washington, yet frost buildup, low refrigerant, faulty reversing valves, or dirty coils can reduce output. If warm air feels weak or the outdoor unit stays iced over, schedule an inspection promptly.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">AC Blowing Warm Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                Summer heat waves can expose tired air conditioners. Warm air usually signals refrigerant leaks, a failed capacitor, a dirty condenser coil, or thermostat issues. Prompt repair prevents small faults from turning into compressor damage.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Smoky or Dusty Indoor Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                Wildfire season can push fine particles indoors. Clogged filters, leaky ducts, and outdated filtration let them circulate. Upgrading filters, sealing ducts, and adding purification can improve what your family breathes every day. Early attention keeps indoor air noticeably healthier throughout the smoke season.
                            </p>
                        </div>
