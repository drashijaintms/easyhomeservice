                        <h2 class="ehs-hvac-section-title">
                            Common Heating and Cooling Problems in Detroit Homes
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Furnace Failing During Cold Snaps</h3>
                            <p class="ehs-hvac-challenges-text">
                                When temperatures drop below freezing, a furnace with worn igniters, dirty flame sensors, or clogged filters can shut down at the worst moment. Frequent cycling, strange noises, or uneven heat are early warnings. Addressing them early, well before deep winter arrives, protects comfort and helps avoid emergency calls and unexpected repair bills.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Air Conditioner Struggling in Humid Summers</h3>
                            <p class="ehs-hvac-challenges-text">
                                Detroit summers can bring long stretches of heat and humidity, pushing air conditioners hard. Low refrigerant, dirty coils, or failing capacitors often cause weak airflow, warm rooms, or a system that runs constantly. A professional diagnosis identifies the cause so you can choose between repair and replacement with confidence and without guesswork.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures in Older Homes</h3>
                            <p class="ehs-hvac-challenges-text">
                                Many Detroit houses have additions, finished basements, or original ductwork that no longer matches the home's layout. The result is cold upstairs bedrooms, stuffy first floors, and rising energy bills and constant thermostat adjustments. Duct inspection, sealing, balancing, or added returns can often improve airflow and comfort without replacing the entire system.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Poor Indoor Air Quality and Dry Winter Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                Sealed-up homes during cold months can trap dust, pet dander, and excess dryness, while basements may hold musty humidity in summer. Worn filters and neglected ducts make this worse. Better filtration, humidity control, and routine maintenance can help your household breathe easier and reduce strain on your heating and cooling equipment.
                            </p>
                        </div>
