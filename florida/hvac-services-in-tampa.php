                            <p class="ehs-hvac-challenges-text">
                                When an AC system runs but delivers warm or insufficiently cool air, possible causes include restricted filters, refrigerant problems, dirty coils, or malfunctioning components. A professional diagnostic visit can help identify the underlying issue.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">High Indoor Humidity</h3>
                            <p class="ehs-hvac-challenges-text">
                                Your home may feel damp or clammy even when the thermostat reaches its setting. Poor moisture removal, oversized equipment, drainage problems, or outside air infiltration can contribute to the issue. 
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Weak Airflow or Uneven Temperatures</h3>
                            <p class="ehs-hvac-challenges-text">
                                Some rooms may remain warm while others cool normally. Blocked filters, duct leakage, blower problems, or airflow imbalances may be responsible.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Water Leaking Near the Indoor Unit</h3>
                            <p class="ehs-hvac-challenges-text">
                              Air conditioners remove moisture during cooling. A clogged condensate drain or drainage issue can cause water to collect around indoor equipment and potentially damage nearby materials.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Frequent Cycling and Rising Energy Bills</h3>
                            <p class="ehs-hvac-challenges-text">
