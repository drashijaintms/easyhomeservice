                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Air Conditioner Blowing Warm Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                A system that runs without cooling properly may have a dirty filter, frozen evaporator coil, refrigerant leak, thermostat issue, or compressor fault. Turn the system off if ice appears and arrange a professional inspection.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Water Leaks Around the Indoor Unit</h3>
                            <p class="ehs-hvac-challenges-text">
                                Florida's humid air creates condensate during cooling. A blocked drain line, damaged drain pan, or frozen coil can lead to water around the air handler. Prompt attention helps limit water damage.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Cooling and Weak Airflow</h3>
                            <p class="ehs-hvac-challenges-text">
                                Bedrooms that stay warm while common areas cool down may have blocked vents, duct leaks, balancing issues, or an equipment problem. A technician can inspect the distribution system rather than treating every room separately.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heat Pump or Heating Malfunctions</h3>
                            <p class="ehs-hvac-challenges-text">
                               A heat pump that cannot maintain the set temperature may have a control, airflow, refrigerant, or reversing-valve issue. Professional diagnosis can determine whether repair or replacement is appropriate.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Rising Bills and Frequent Cycling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Unexpected energy costs or repeated starts and stops can result from dirty components, incorrect sizing, thermostat problems, duct leakage, or failing equipment. Inspection helps narrow down the cause before parts are replaced.
