                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">AC Running Nonstop Without Cooling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Low refrigerant, dirty coils, or a failing compressor can leave your system working all day while rooms stay warm. Early diagnosis often prevents a minor repair from becoming a full breakdown.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Excess Humidity and Musty Odors</h3>
                            <p class="ehs-hvac-challenges-text">
                                Tallahassee’s moist air can overwork an undersized or aging system, leaving rooms clammy. Clogged drain lines and dirty ducts may also contribute to stale smells and mold concerns.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Pollen-Clogged Filters and Coils</h3>
                            <p class="ehs-hvac-challenges-text">
                                Spring pollen from pines and oaks coats filters quickly, restricting airflow and straining your blower. Regular filter changes and professional cleaning help keep air moving and equipment protected.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Storm Damage and Power Surges</h3>
                            <p class="ehs-hvac-challenges-text">
                                Frequent summer thunderstorms and hurricane-season outages can damage capacitors, control boards, and compressors. A technician can inspect electrical components and discuss surge protection options for your system.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures and High Energy Bills</h3>
                            <p class="ehs-hvac-challenges-text">
                                Leaky ductwork, poor insulation, and aging equipment force your system to work harder. Hot upstairs rooms or climbing utility bills often signal airflow or efficiency problems worth checking.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Short Cycling and Strange Noises</h3>
                            <p class="ehs-hvac-challenges-text">
                                Frequent on-and-off cycles, rattling, or grinding sounds are not normal for a properly working system. They can point to worn parts, refrigerant issues, or airflow restrictions, so an early inspection is often wiser than waiting.
                            </p>
                        </div>
