    <section class="ehs-hvac-challenges-section">
        <div class="container">
            <div class="row justify-content-center">

                <div class="col-12 col-lg-8">
                    <div class="ehs-hvac-challenges-container">

                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems in Tucson Homes
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Air Conditioner Running but Not Cooling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Long triple-digit stretches keep compressors and fans working almost nonstop. Low refrigerant, dirty coils, failing capacitors, or a tired blower motor can leave the house warm while the outdoor unit hums. Caught early, many of these are repairable; waiting often turns a small fix into a system failure during peak heat.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Dust-Clogged Filters and Coils</h3>
                            <p class="ehs-hvac-challenges-text">
                                Desert dust and monsoon wind-blown grit coat filters, evaporator coils, and condenser fins faster than many homeowners expect. Restricted airflow strains the system, raises energy use, and can freeze the indoor coil. Regular filter changes and professional coil cleaning help protect efficiency and equipment life.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures Room to Room</h3>
                            <p class="ehs-hvac-challenges-text">
                                Hot bedrooms and cool living rooms often point to leaking or poorly insulated ducts, especially in attics where summer temperatures soar. Duct leaks waste conditioned air before it reaches vents. A duct inspection, sealing, or airflow balancing can restore comfort without replacing equipment.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heating That Fails When Winter Finally Arrives</h3>
                            <p class="ehs-hvac-challenges-text">
                                Tucson winters are mild, which means furnaces and heat pumps sit idle for months. When the first cold night arrives, ignition problems, worn blower parts, or a reversing valve fault can leave you without heat. A fall inspection can catch these issues before the season turns.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Short Cycling and Rising Bills</h3>
                            <p class="ehs-hvac-challenges-text">
                                A system that starts and stops repeatedly, or bills that climb unexpectedly, often point to sizing issues, sensor trouble, or declining parts.
                            </p>
                        </div>

                        <div class="ehs-hvac-challenges-callout">
                            <p class="ehs-hvac-challenges-callout-text">
                                Addressing HVAC problems early can help protect comfort and reduce the risk of further equipment damage. If your system shows persistent warning signs, consider arranging a professional inspection rather than waiting for a complete breakdown.
                            </p>
