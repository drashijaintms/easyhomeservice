                            <p class="ehs-hvac-challenges-text">
                               When an AC unit runs continuously without adequately cooling your home, possible causes include a clogged air filter, dirty coils, restricted airflow, thermostat issues, or a refrigerant problem. Because Mesa summers put substantial demand on cooling equipment, persistent symptoms deserve prompt attention.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures Between Rooms</h3>
                            <p class="ehs-hvac-challenges-text">
                                A cool living room and a warm upstairs bedroom can indicate duct leakage, insufficient airflow, insulation gaps, or an improperly balanced system. An HVAC assessment can help identify the underlying cause rather than treating individual rooms as separate problems.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Strange Noises or Unusual Odors</h3>
                            <p class="ehs-hvac-challenges-text">
                                Grinding, rattling, buzzing, or persistent unusual odors can signal mechanical, electrical, airflow, or other equipment concerns. Turn the system off if you notice burning smells or signs of electrical trouble, and seek appropriate professional assistance.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heating Problems During Cooler Weather</h3>
                            <p class="ehs-hvac-challenges-text">
                               A furnace that fails to start or a heat pump that struggles to maintain the set temperature may need thermostat checks, airflow corrections, component repairs, or further diagnosis. Addressing heating concerns before cold nights arrive helps homeowners plan service without waiting for a complete failure.
                            </p>
                        </div>
                                                <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Frequent Cycling or Weak Airflow</h3>
