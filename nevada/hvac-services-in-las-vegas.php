    <section class="ehs-hvac-challenges-section">
        <div class="container">
            <div class="row justify-content-center">
                <div class="col-12 col-lg-8">
                    <div class="ehs-hvac-challenges-container">

                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems in Las Vegas Homes
                        </h2>
                        <p>These issues show up often in valley homes, and most are easier to resolve when caught early.</p>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Air Conditioner Running but Not Cooling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Constant summer operation wears components quickly. Low refrigerant, dirty coils, or failing capacitors can leave airflow warm even while the unit runs. A technician can test pressures and electrical parts to find the real cause before recommending any repair.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Frozen Evaporator Coil or Weak Airflow</h3>
                            <p class="ehs-hvac-challenges-text">
                                Dust-laden filters and restricted airflow can cause coils to ice over, and water spills out when the ice melts. Changing filters regularly and scheduling coil cleaning can reduce the likelihood of this common problem.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">High Energy Bills and Short Cycling</h3>
                            <p class="ehs-hvac-challenges-text">
                                A system that turns on and off too frequently may be oversized, poorly maintained, or struggling with a control issue. Short cycling adds wear and can raise energy use, so it deserves a professional inspection. Our team checks airflow, controls, and equipment sizing to find the true cause.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heating Failures on Cold Desert Nights</h3>
                            <p class="ehs-hvac-challenges-text">
                                Because heaters sit idle for months, ignition problems, worn blower motors, or clogged filters often appear at the first cold snap. Las Vegas winter nights can drop near freezing, so a fall inspection is worthwhile.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures and Leaky Ducts</h3>
                            <p class="ehs-hvac-challenges-text">
                                Hot rooms upstairs or in sun-facing bedrooms often point to duct leaks, poor insulation, or imbalanced airflow. Attic ducts in Las Vegas homes face extreme temperatures, which can degrade seals and insulation over time.
                            </p>
                        </div>
