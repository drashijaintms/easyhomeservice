                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Pollen and Poor Indoor Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                Spring pollen and mold spores in the Ohio Valley can overwhelm dirty filters and ducts. Sneezing, dusty surfaces, and musty odors often point to clogged filters, leaky ducts, or moisture trapped inside the system.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Furnace Not Heating Evenly</h3>
                            <p class="ehs-hvac-challenges-text">
                                Cold snaps expose weak furnaces quickly. Cold rooms, strange noises, frequent cycling, or a pilot or ignition failure usually signal worn parts, restricted airflow, or overdue maintenance. Addressing these signs early can prevent a no-heat emergency on the coldest night.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">High Energy Bills and Leaky Ducts</h3>
