    function setDismissed() {
      const until = Date.now() + DISMISS_DAYS * 24 * 60 * 60 * 1000;
      localStorage.setItem(STORAGE_KEY, String(until));
    }
    function isDismissed() {
      const v = localStorage.getItem(STORAGE_KEY);
      if(!v) return false;
      return Date.now() < Number(v);
    }

    // show modal
    function showModal() {
      if(isDismissed()) return;
      backdrop.style.display = 'flex';
      backdrop.setAttribute('aria-hidden','false');
      setTimeout(()=> modal.classList.add('show'), 10);
    }
    function hideModal() {
      modal.classList.remove('show');
      backdrop.setAttribute('aria-hidden','true');
      setTimeout(()=> backdrop.style.display = 'none', 240);
    }

    // close handlers
    closeBtn.addEventListener('click', function(){
      if(dontShowCheckbox.checked) setDismissed();
      hideModal();
    });
    modalContinue.addEventListener('click', function(e){
      e.preventDefault();
      if(dontShowCheckbox.checked) setDismissed();
      hideModal();
    });
    // clicking backdrop closes too
    backdrop.addEventListener('click', function(e){
      if(e.target === backdrop){
        if(dontShowCheckbox.checked) setDismissed();
        hideModal();
      }
    });

    // modal CTA sends to affiliate (analytics hook)
    modalCta.addEventListener('click', function(){
      console.log('Popup CTA clicked:', new Date().toISOString());
      // gtag/fbq event code goes here if needed
    });

    // EXIT INTENT DETECTION (desktop): mouse leaves to top
    let exitIntentShown = false;
    function handleMouseOut(e) {
      // If mouse moves to top of viewport and not yet shown
      if (e.clientY <= 0 && !exitIntentShown) {
        exitIntentShown = true;
        showModal();
      }
    }
    document.addEventListener('mouseout', handleMouseOut);

    // Also detect visibility change (tab close / mobile)
    document.addEventListener('visibilitychange', function(){
      if (document.visibilityState === 'hidden' && !exitIntentShown) {
        exitIntentShown = true;
        showModal();
      }
    });

    // On mobile, if user taps back or tries to leave, visibilitychange will catch; also we fallback to showing after 12s of idle
    let idleTimer;
    function startIdleTimer(){
      clearTimeout(idleTimer);
      idleTimer = setTimeout(function(){
        if(!exitIntentShown && !isDismissed()){
          // show a gentle reminder popup after idle on mobile
          exitIntentShown = true;
          showModal();
        }
      }, 12000);
    }
    ['mousemove','touchstart','scroll','keydown'].forEach(evt => {
      document.addEventListener(evt, startIdleTimer, {passive:true});
    });
    startIdleTimer();

    // accessibility: focus trap-ish (simple)
    // Move focus to modal when shown
    const observer = new MutationObserver(function(){
      if (backdrop.style.display === 'flex') {
        modalCta.focus();
      }
    });
    observer.observe(backdrop, { attributes:true, attributeFilter:['style'] });

    // ensure external affiliate links always have utm - if later added dynamically
    function ensureAffiliates() {
      document.querySelectorAll('a').forEach(a=>{
        try {
          const href = a.getAttribute('href') || '';
          if (href.startsWith('https://qualitywindowsdirect.com')) {
            a.setAttribute('href', AFF_URL);
          }
        } catch(e){}
      });
    }
    ensureAffiliates();

    // Simple console notice (remove if you prefer silent)
    console.log('EasyHomeService prelander loaded — Affiliate URL:', AFF_URL);
