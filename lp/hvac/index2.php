      if (ENABLE_POST) {
        const data = new URLSearchParams({
          firstName: lead.firstName || "",
          lastName: lead.lastName || "",
          email: lead.email || "",
          zip: (lead.zip || "").toString(),
          phone: (lead.phone || "").replace(/\D/g, ""),
          problem: lead.problem || "",
        });
        try {
          await fetch(ENDPOINT, { method: "POST", body: data });
        } catch (err) {
          console.error("POST Error", err);
        }
      }
      if (msg) botReply(msg);
    }

    // --- Handle user answers ---
    function handleAnswer(textRaw) {
      const text = textRaw.trim();
      if (!text) return;
      const p = document.createElement("p");
      p.className = "user-msg";
      p.textContent = text;
      chatBody.appendChild(p);
      chatBody.scrollTop = chatBody.scrollHeight;

// --- Default response after chat ends ---
if (callbackActive && stepIndex >= steps.length) {
botReply(`If you need anything else, <a href="tel:${CALL_NUMBER_E164}" class="text-success fw-bold">call ${CALL_NUMBER_DISPLAY}</a>.`);
