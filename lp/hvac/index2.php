  // --- Handle Skip Email button ---
  if (e.target && e.target.id === "skipEmailBtn") {
    e.preventDefault();
    const cur = steps[stepIndex];
    if (cur && cur.key === "email") {
      lead.email = "";
      stepIndex++;

      // Custom skip email response
      botReply("No worries! Let’s move on.");
      setTimeout(() => {
        botReply(`<p class="bot-msg alert alert-success">Thanks <strong>${escapeHtml(lead.firstName)}</strong>! For faster service, it’s best to <strong>call us right now</strong> — our technician can help you immediately.</p>`);
