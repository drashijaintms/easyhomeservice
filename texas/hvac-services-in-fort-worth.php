                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems in Fort Worth Homes
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">AC Struggling in Triple-Digit Heat</h3>
                            <p class="ehs-hvac-challenges-text">
                                When temperatures stay above 100 degrees for days, an undersized or neglected system may run constantly and still fall short. Dirty coils, low refrigerant from a leak, or failing capacitors are frequent causes. Catching weak airflow or warm vents early can prevent a full breakdown during the hottest stretch of summer.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Ductwork Affected by Shifting Soil</h3>
                            <p class="ehs-hvac-challenges-text">
                                Parts of Fort Worth sit on expansive clay soil that swells and shrinks with moisture. Over time, foundation movement can loosen duct connections or crush flexible runs in crawlspaces and attics. The result is uneven rooms, higher energy use, and dust circulating through the home. A duct inspection often reveals the cause.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Heating Failures During Cold Snaps</h3>
                            <p class="ehs-hvac-challenges-text">
                                Furnaces often sit idle for months, then face sudden, heavy demand when a North Texas cold front arrives. Ignition problems, cracked heat exchangers, and clogged filters are common culprits. Because gas heating carries safety considerations, unusual smells, short cycling, or yellow pilot flames deserve prompt professional attention rather than a wait-and-see approach.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Hail, Pollen, and Airflow Concerns</h3>
                            <p class="ehs-hvac-challenges-text">
                                Spring hailstorms can bend condenser fins and reduce cooling performance, while heavy pollen seasons clog filters faster than expected. Restricted airflow forces blowers to work harder and can allow indoor coils to freeze. Regular filter changes and a prompt post-storm equipment check help protect efficiency and extend the life of your system.
                            </p>
                        </div>
