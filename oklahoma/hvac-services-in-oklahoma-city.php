                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems in Oklahoma City Homes
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">AC Blowing Warm Air</h3>
                            <p class="ehs-hvac-challenges-text">
                                When triple-digit afternoons arrive, a system that runs without cooling often points to low refrigerant, a failing capacitor, or a dirty evaporator coil. Windblown dust and cottonwood fluff common in Oklahoma can coat outdoor coils, trapping heat and reducing cooling performance.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Furnace Short Cycling or Failing to Ignite</h3>
                            <p class="ehs-hvac-challenges-text">
                                Many Oklahoma furnaces sit idle for months, then face a sudden November cold front. Clogged filters, worn hot surface igniters, and faulty flame sensors are frequent reasons for a furnace that turns on and off quickly or fails to produce heat.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Storm and Power Surge Damage</h3>
                            <p class="ehs-hvac-challenges-text">
                                Severe spring thunderstorms and lightning can send sudden electrical surges through outdoor units, control boards, and compressors. Hail may also bend delicate condenser fins, restricting airflow. A post-storm inspection helps catch damage early, before it becomes a larger and costlier repair.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures from Room to Room</h3>
                            <p class="ehs-hvac-challenges-text">
                                Hot upstairs bedrooms or a cold back room often trace back to leaky ducts, poor attic insulation, or an improperly sized system. Because many homes here have ducts running through hot attics, even small leaks can waste significant amounts of cooled air.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">High Humidity and Poor Indoor Air Quality</h3>
                            <p class="ehs-hvac-challenges-text">
                                Oklahoma's humid stretches, combined with seasonal pollen from cedar, oak, and grasses, can leave indoor air feeling sticky or stale. Oversized air conditioners, dirty filters, and unsealed ducts often make the problem worse, and may encourage musty odors in closets and bathrooms.
                            </p>
                        </div>
