    <section class="ehs-hvac-challenges-section">
        <div class="container">
            <div class="row justify-content-center">
                <div class="col-12 col-lg-8">
                    <div class="ehs-hvac-challenges-container">
                        <h2 class="ehs-hvac-section-title">
                            Common HVAC Problems Kansas City Homeowners Face
                        </h2>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Air Conditioner Running but Not Cooling</h3>
                            <p class="ehs-hvac-challenges-text">
                                Long, humid stretches push central air to its limits. Low refrigerant, a dirty coil, a failing capacitor, or restricted airflow can leave rooms warm even while the system runs. Early service often prevents a small issue from becoming a breakdown.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Furnace Short Cycling or Failing to Ignite</h3>
                            <p class="ehs-hvac-challenges-text">
                                When January cold settles in, a furnace that starts and stops repeatedly or won’t light needs attention. Common causes include clogged filters, faulty igniters or flame sensors, and thermostat problems. Never ignore a gas smell; leave the home and call your utility.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Uneven Temperatures Between Floors</h3>
                            <p class="ehs-hvac-challenges-text">
                                Two-story homes and finished basements often struggle with hot upstairs rooms and cold lower levels. Leaky or poorly balanced ductwork, blocked returns, and insufficient insulation commonly contribute, and a duct and airflow inspection can pinpoint the source.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Rising Energy Bills</h3>
                            <p class="ehs-hvac-challenges-text">
                                A system that is running longer than it used to may be signaling trouble. Worn components, dirty filters, aging equipment, and duct leakage all force heating and cooling systems to work harder, so a tune-up is a practical first step.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-block">
                            <h3 class="ehs-hvac-challenges-subtitle">Frozen Coils and Humidity Issues</h3>
                            <p class="ehs-hvac-challenges-text">
                                Ice on the indoor coil or a clammy feeling at home often points to airflow restrictions or refrigerant issues. Turn the system off to let ice melt, then schedule service rather than running it until it fails. Persistent moisture can also encourage musty odors and mold growth indoors.
                            </p>
                        </div>
                        <div class="ehs-hvac-challenges-callout">
                            <p class="ehs-hvac-challenges-callout-text">
