document.addEventListener("DOMContentLoaded", function () {
    const faqItems = document.querySelectorAll(".ehs-hvac-faq-item");

    // Initialize first active item height smoothly
    faqItems.forEach(function (item) {
        const body = item.querySelector(".ehs-hvac-faq-body");
        if (item.classList.contains("active")) {
            body.style.maxHeight = body.scrollHeight + "px";
        } else {
            body.style.maxHeight = "0px";
        }
    });

    faqItems.forEach(function (item) {
        const header = item.querySelector(".ehs-hvac-faq-header");
        const body = item.querySelector(".ehs-hvac-faq-body");
        const icon = item.querySelector(".ehs-hvac-faq-icon i");

        header.addEventListener("click", function () {
            const isActive = item.classList.contains("active");

            // Close all other items smoothly
            faqItems.forEach(function (otherItem) {
                if (otherItem !== item && otherItem.classList.contains("active")) {
                    otherItem.classList.remove("active");
                    otherItem.querySelector(".ehs-hvac-faq-header").setAttribute("aria-expanded", "false");
                    const otherBody = otherItem.querySelector(".ehs-hvac-faq-body");
                    if (otherBody) {
                        otherBody.style.maxHeight = "0px";
                    }
                    const otherIcon = otherItem.querySelector(".ehs-hvac-faq-icon i");
                    if (otherIcon) {
                        otherIcon.className = "fa-solid fa-plus";
                    }
                }
            });

            // Toggle clicked item
            if (isActive) {
                item.classList.remove("active");
                header.setAttribute("aria-expanded", "false");
                body.style.maxHeight = "0px";
                if (icon) {
                    icon.className = "fa-solid fa-plus";
                }
            } else {
                item.classList.add("active");
                header.setAttribute("aria-expanded", "true");
                body.style.maxHeight = body.scrollHeight + "px";
                if (icon) {
                    icon.className = "fa-solid fa-xmark";
                }
            }
        });
    });
});
</script>
